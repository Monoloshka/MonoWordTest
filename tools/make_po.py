#!/bin/sh
''''exec python3 "$0" "$@" # '''
"""Convert languages/*.json into standard gettext files (stdlib only, no gettext tools needed).

  python3 tools/make_po.py

writes   po/monowordtest.pot          template (all English source texts)
         po/<code>.po                 one editable catalogue per language
         build/locale/<code>/LC_MESSAGES/monowordtest.mo     compiled catalogues

The Flatpak build installs build/locale/ to /app/share/locale/ (the standard gettext location);
the Electron wrapper reads the .mo files from there. languages/*.json stay the source of truth;
everywhere else (browser, Android, OpenWrt, Windows ...) the same files are imported by the user.
"""
import json, os, re, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOMAIN = 'monowordtest'
VERSION = json.load(open(os.path.join(ROOT, 'package.json'), encoding='utf-8'))['version']

def po_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t')


def parse_translations():
    langs = {}
    folder = os.path.join(ROOT, 'languages')
    for fn in sorted(os.listdir(folder)):
        if not fn.endswith('.json') or fn == 'template.json':
            continue
        data = json.load(open(os.path.join(folder, fn), encoding='utf-8-sig'))
        for code, L in data.items():
            if code in langs:
                print('warning: language "%s" in %s ignored (already defined)' % (code, fn))
                continue
            strings = {k: v for k, v in L.get('strings', {}).items() if isinstance(k, str) and isinstance(v, str)}
            langs[code] = {'name': str(L.get('name', code)), 'flag': str(L.get('flag', '')), 'strings': strings}
    if not langs:
        sys.exit('languages/: no language files found')
    return langs


def gettext_code(code):                    # 'pt-br' -> 'pt_BR', 'ru' -> 'ru'
    p = code.replace('_', '-').split('-')
    return p[0].lower() + ('_' + p[1].upper() if len(p) > 1 else '')


def header(code, name, flag):
    lines = ['Project-Id-Version: %s %s' % (DOMAIN, VERSION), 'Language: %s' % code,
             'MIME-Version: 1.0', 'Content-Type: text/plain; charset=UTF-8', 'Content-Transfer-Encoding: 8bit',
             'X-MWT-Name: %s' % name, 'X-MWT-Flag: %s' % flag]
    return ''.join(l + '\n' for l in lines)


def write_po(path, hdr, keys, strings):
    out = ['# MonoWordTest translation. Generated by tools/make_po.py from languages/*.json.\n',
           'msgid ""\nmsgstr ""\n']
    out += ['"%s\\n"\n' % po_escape(l) for l in hdr.rstrip('\n').split('\n')]
    for k in keys:
        out.append('\nmsgid "%s"\nmsgstr "%s"\n' % (po_escape(k), po_escape(strings.get(k, ''))))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8', newline='\n').write(''.join(out))


def write_mo(path, entries):
    keys = sorted(entries, key=lambda k: k.encode('utf-8'))
    ids, strs, offs = b'', b'', []
    for k in keys:
        kb, vb = k.encode('utf-8'), entries[k].encode('utf-8')
        offs.append((len(ids), len(kb), len(strs), len(vb)))
        ids += kb + b'\0'
        strs += vb + b'\0'
    n = len(keys)
    keystart = 7 * 4 + 16 * n
    valuestart = keystart + len(ids)
    kt, vt = [], []
    for o1, l1, o2, l2 in offs:
        kt += [l1, o1 + keystart]
        vt += [l2, o2 + valuestart]
    data = struct.pack('<Iiiiiii', 0x950412de, 0, n, 7 * 4, 7 * 4 + n * 8, 0, 0)
    data += struct.pack('<%di' % len(kt + vt), *(kt + vt)) + ids + strs
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'wb').write(data)


def main():
    langs = parse_translations()
    keys = []
    for code, L in langs.items():                       # union of all source texts, in file order
        for k in L['strings']:
            if k not in keys:
                keys.append(k)
    write_po(os.path.join(ROOT, 'po', DOMAIN + '.pot'), header('', '', ''), keys, {})
    count = 0
    for code, L in langs.items():
        if not L['strings']:
            continue                                     # English: the source text, nothing to translate
        gc = gettext_code(code)
        hdr = header(gc, L['name'], L['flag'])
        write_po(os.path.join(ROOT, 'po', gc + '.po'), hdr, keys, L['strings'])
        entries = {'': hdr}
        entries.update((k, v) for k, v in L['strings'].items() if v)
        write_mo(os.path.join(ROOT, 'build', 'locale', gc, 'LC_MESSAGES', DOMAIN + '.mo'), entries)
        count += 1
    print('wrote po/%s.pot, %d x .po and %d x build/locale/*/LC_MESSAGES/%s.mo' % (DOMAIN, count, count, DOMAIN))


if __name__ == '__main__':
    main()
