#!/bin/sh
''''exec python3 "$0" "$@" # '''
"""Build sounds.js from sounds/sounds.txt (event | file.mp3). Files stay next to the app and are played by relative URL."""
import os, sys, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, 'sounds')
EVENTS = ('correct', 'wrong', 'start', 'builtin', 'menu', 'exit')
out = {}
with open(os.path.join(DIR, 'sounds.txt'), encoding='utf-8-sig') as f:
    for n, line in enumerate(f, 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        p = [x.strip() for x in line.split('|')]
        if len(p) < 2 or p[0] not in EVENTS:
            sys.exit('sounds.txt line %d: expected "<%s> | file.mp3"' % (n, '/'.join(EVENTS)))
        if not p[1].lower().endswith('.mp3'):
            sys.exit('sounds.txt line %d: only .mp3 is supported' % n)
        if not os.path.isfile(os.path.join(DIR, p[1])):
            sys.exit('sounds.txt line %d: file not found: sounds/%s' % (n, p[1]))
        out[p[0]] = 'sounds/' + p[1]
with open(os.path.join(ROOT, 'sounds.js'), 'w', encoding='utf-8') as f:
    f.write('/* GENERATED by tools/build_sounds.py from sounds/sounds.txt - do not edit by hand. */\n')
    f.write('var MWT_SOUNDS = ' + json.dumps(out, indent=1) + ';\n')
print('wrote sounds.js with %d event(s)' % len(out))
