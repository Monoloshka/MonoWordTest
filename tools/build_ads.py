#!/usr/bin/env python3
"""Embed the banner images listed in ads/ads.txt into ads.js (images are baked
into the app as data URIs - nothing is loaded from the internet at run time)."""
import base64, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADS_DIR = os.path.join(ROOT, 'ads')
MIME = {'.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg',
        '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp'}

ads = []
with open(os.path.join(ADS_DIR, 'ads.txt'), encoding='utf-8-sig') as f:
    for n, line in enumerate(f, 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        parts = [p.strip() for p in line.split('|')]
        if len(parts) < 2:
            sys.exit('ads.txt line %d: expected "file | url | alt"' % n)
        name, url = parts[0], parts[1]
        alt = parts[2] if len(parts) > 2 else ''
        ext = os.path.splitext(name)[1].lower()
        if ext not in MIME:
            sys.exit('ads.txt line %d: unsupported image type %s' % (n, ext))
        if not (url.startswith('http://') or url.startswith('https://')):
            sys.exit('ads.txt line %d: link must start with http:// or https://' % n)
        path = os.path.join(ADS_DIR, name)
        if not os.path.isfile(path):
            sys.exit('ads.txt line %d: file not found: %s' % (n, path))
        with open(path, 'rb') as img:
            raw = img.read()
        if len(raw) > 500 * 1024:
            print('warning: %s is %d KB - consider shrinking it' % (name, len(raw) // 1024))
        ads.append({'mime': MIME[ext], 'data': base64.b64encode(raw).decode('ascii'),
                    'url': url, 'alt': alt})

out = os.path.join(ROOT, 'ads.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* GENERATED by tools/build_ads.py from ads/ads.txt - do not edit by hand. */\n')
    f.write('var MWT_ADS = ' + json.dumps(ads, ensure_ascii=True, indent=1) + ';\n')
print('wrote %s with %d ad(s)' % (out, len(ads)))
