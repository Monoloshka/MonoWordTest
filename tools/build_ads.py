#!/bin/sh
''''exec python3 "$0" "$@" # '''
"""Build ads.js from ads/ads.txt. Images are embedded as base64 data URIs (nothing is loaded from the internet).

  python3 tools/build_ads.py                          -> ads.js (banners + text ads)
  python3 tools/build_ads.py --text-only --out FILE   -> text links only, no images (used for the OpenWrt package)

ads.txt line:  image file | https://link | alt text      (use  -  instead of an image file for a text-only ad)
"""
import argparse, base64, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADS_DIR = os.path.join(ROOT, 'ads')
MIME = {'.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg',
        '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp'}

ap = argparse.ArgumentParser()
ap.add_argument('--text-only', action='store_true', help='drop images, keep link + text')
ap.add_argument('--out', default=os.path.join(ROOT, 'ads.js'))
args = ap.parse_args()

ads = []
with open(os.path.join(ADS_DIR, 'ads.txt'), encoding='utf-8-sig') as f:
    for n, line in enumerate(f, 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        parts = [p.strip() for p in line.split('|')]
        if len(parts) < 2:
            sys.exit('ads.txt line %d: expected "file | url | text"' % n)
        name, url = parts[0], parts[1]
        alt = parts[2] if len(parts) > 2 else ''
        if not (url.startswith('http://') or url.startswith('https://')):
            sys.exit('ads.txt line %d: link must start with http:// or https://' % n)
        entry = {'url': url, 'alt': alt}
        if name != '-' and not args.text_only:
            ext = os.path.splitext(name)[1].lower()
            if ext not in MIME:
                sys.exit('ads.txt line %d: unsupported image type %s' % (n, ext))
            path = os.path.join(ADS_DIR, name)
            if not os.path.isfile(path):
                sys.exit('ads.txt line %d: file not found: %s' % (n, path))
            with open(path, 'rb') as img:
                raw = img.read()
            if len(raw) > 500 * 1024:
                print('warning: %s is %d KB - consider shrinking it' % (name, len(raw) // 1024))
            entry['mime'] = MIME[ext]
            entry['data'] = base64.b64encode(raw).decode('ascii')
        elif not alt:
            print('warning: ads.txt line %d is a text ad without text; the host name will be shown' % n)
        ads.append(entry)

with open(args.out, 'w', encoding='utf-8') as f:
    f.write('/* GENERATED by tools/build_ads.py from ads/ads.txt - do not edit by hand. */\n')
    f.write('var MWT_ADS = ' + json.dumps(ads, ensure_ascii=True, indent=1) + ';\n')
print('wrote %s with %d ad(s)%s' % (args.out, len(ads), ' (text only)' if args.text_only else ''))
