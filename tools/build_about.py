#!/bin/sh
''''exec python3 "$0" "$@" # '''
"""Build about.js (About screen data) from about/about.txt, package.json (version) and build/icon.png.

  python3 tools/build_about.py            write about.js
  python3 tools/build_about.py --check    exit 1 if about.js has a different version than package.json
"""
import base64, io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ABOUT = os.path.join(ROOT, 'about')
MIME = {'.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
        '.gif': 'image/gif', '.webp': 'image/webp', '.ico': 'image/x-icon'}
version = json.load(open(os.path.join(ROOT, 'package.json'), encoding='utf-8'))['version']
out_path = os.path.join(ROOT, 'about.js')

if '--check' in sys.argv:
    try:
        cur = re.search(r'"version":\s*"([^"]*)"', open(out_path, encoding='utf-8').read()).group(1)
    except Exception:
        cur = None
    if cur != version:
        sys.exit('about.js has version %s but package.json has %s - run: python3 tools/build_about.py' % (cur, version))
    print('about.js is up to date (%s)' % version)
    sys.exit(0)


def data_uri(path, mime):
    return 'data:%s;base64,%s' % (mime, base64.b64encode(open(path, 'rb').read()).decode('ascii'))


def app_icon():
    path = os.path.join(ROOT, 'build', 'icon.png')
    try:
        from PIL import Image
        im = Image.open(path).convert('RGBA').resize((192, 192), Image.LANCZOS)
        buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True)
        return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode('ascii')
    except ImportError:
        print('note: Pillow not installed, embedding build/icon.png at full size')
        return data_uri(path, 'image/png')


author, links = '', []
with open(os.path.join(ABOUT, 'about.txt'), encoding='utf-8-sig') as f:
    for n, line in enumerate(f, 1):
        line = line.rstrip('\r\n')
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if line.lower().startswith('author:'):
            author = line.split(':', 1)[1].strip()
            continue
        p = [x.strip() for x in line.split('|')]
        text = p[0]
        url = p[1] if len(p) > 1 else ''
        icon = p[2] if len(p) > 2 else ''
        if url and not re.match(r'^https?://', url):
            sys.exit('about.txt line %d: link must start with http:// or https://' % n)
        entry = {'text': text}
        if url:
            entry['url'] = url
        if icon:
            ext = os.path.splitext(icon)[1].lower()
            path = os.path.join(ABOUT, icon)
            if ext not in MIME or not os.path.isfile(path):
                sys.exit('about.txt line %d: icon not found or unsupported: %s' % (n, icon))
            entry['icon'] = data_uri(path, MIME[ext])
        links.append(entry)

data = {'version': version, 'author': author, 'icon': app_icon(), 'links': links}
with open(out_path, 'w', encoding='utf-8') as f:
    f.write('/* GENERATED by tools/build_about.py - do not edit by hand. */\n')
    f.write('var MWT_ABOUT = ' + json.dumps(data, ensure_ascii=True, indent=1) + ';\n')
print('wrote about.js (version %s, %d line(s))' % (version, len(links)))
